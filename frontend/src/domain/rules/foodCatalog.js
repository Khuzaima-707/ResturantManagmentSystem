export function findCatalogFood(foodName = '', categoryName = '') {
  if (!foodName && !categoryName) return null;

  const fNorm = (foodName || '').trim().toLowerCase();
  const cNorm = (categoryName || '').trim().toLowerCase();

  // 1. Exact Name Match
  if (fNorm) {
    const exact = FOOD_CATALOG.find((item) => item.name.toLowerCase() === fNorm);
    if (exact) return exact;
  }

  // 2. Substring or multi-word match
  if (fNorm) {
    const candidates = FOOD_CATALOG.filter((item) => {
      const itemLow = item.name.toLowerCase();
      return fNorm.includes(itemLow) || itemLow.includes(fNorm);
    }).sort((a, b) => b.name.length - a.name.length);

    if (candidates.length > 0) {
      if (cNorm) {
        const catMatch = candidates.find((c) => c.category.toLowerCase().includes(cNorm) || cNorm.includes(c.category.toLowerCase()));
        if (catMatch) return catMatch;
      }
      return candidates[0];
    }
  }

  // 3. Category Fallback Match
  if (cNorm) {
    const catDefault = FOOD_CATALOG.find((item) => item.category.toLowerCase().includes(cNorm) || cNorm.includes(item.category.toLowerCase()));
    if (catDefault) return catDefault;
  }

  return null;
}
